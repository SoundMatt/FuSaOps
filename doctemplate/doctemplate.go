// Package doctemplate generates safety documentation templates for
// multi-language projects in Markdown format.
//
// Generate selects templates from the standard library by the requested
// safety standards (ISO 26262, DO-178C, IEC 61508, ISO 21434) and writes
// them as Markdown files to an output directory. A Report documents what was
// generated, which can be persisted and rendered as text or JSON.
package doctemplate

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"time"

	fusaops "github.com/SoundMatt/FuSaOps"
)

// ReportFile is the default filename for the persisted template report.
//
//fusa:req REQ-FO-TMPL001
const ReportFile = ".fusaops-templates.json"

// DefaultOutputDir is the default subdirectory for generated template files.
//
//fusa:req REQ-FO-TMPL001
const DefaultOutputDir = "safety-docs"

// DocKind classifies the purpose of a safety document template.
//
//fusa:req REQ-FO-TMPL001
type DocKind string

const (
	DocKindPlan         DocKind = "plan"
	DocKindRequirements DocKind = "requirements"
	DocKindReport       DocKind = "report"
	DocKindChecklist    DocKind = "checklist"
)

// DocTemplate holds the definition of one safety document template.
//
//fusa:req REQ-FO-TMPL001
type DocTemplate struct {
	ID        string   `json:"id"`
	Name      string   `json:"name"`
	Kind      DocKind  `json:"kind"`
	Standards []string `json:"standards"` // empty means "all standards"
	Filename  string   `json:"filename"`
	Content   string   `json:"-"` // not serialised — content is on disk after generation
}

// GeneratedDoc records one template file that was written to disk.
//
//fusa:req REQ-FO-TMPL001
type GeneratedDoc struct {
	TemplateID string `json:"templateId"`
	Name       string `json:"name"`
	Path       string `json:"path"`
	Size       int64  `json:"size"`
}

// Report is the top-level document generation report.
//
//fusa:req REQ-FO-TMPL001
type Report struct {
	GeneratedAt    time.Time      `json:"generatedAt"`
	ProjectRoot    string         `json:"projectRoot"`
	Tool           string         `json:"tool"`
	ToolVersion    string         `json:"toolVersion"`
	OutputDir      string         `json:"outputDir"`
	Standards      []string       `json:"standards"`
	Generated      []GeneratedDoc `json:"generated"`
	TotalGenerated int            `json:"totalGenerated"`
	Hash           string         `json:"hash"`
}

