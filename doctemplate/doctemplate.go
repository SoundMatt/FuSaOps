// applicableTemplates returns templates that apply to the requested standards.
// If standards is empty, all templates are returned.
func applicableTemplates(standards []string) []DocTemplate {
	if len(standards) == 0 {
		return standardTemplates
	}
	stdSet := make(map[string]bool, len(standards))
	for _, s := range standards {
		stdSet[strings.ToLower(s)] = true
	}
	var out []DocTemplate
	for _, t := range standardTemplates {
		if len(t.Standards) == 0 {
			out = append(out, t)
			continue
		}
		for _, ts := range t.Standards {
			if stdSet[strings.ToLower(ts)] {
				out = append(out, t)
				break
			}
		}
	}
	return out
}

// Generate writes safety documentation templates to outputDir under root.
// standards filters which templates to generate; empty means generate all.
//
//fusa:req REQ-FO-TMPL002
func Generate(root, outputDir string, standards []string) (*Report, error) {
	r := &Report{
		GeneratedAt: time.Now().UTC(),
		ProjectRoot: root,
		Tool:        "fusaops",
		ToolVersion: fusaops.Version,
		OutputDir:   outputDir,
		Standards:   standards,
	}
	if len(standards) == 0 {
		r.Standards = []string{"all"}
	}

	if err := os.MkdirAll(outputDir, 0o750); err != nil {
		return nil, fmt.Errorf("doctemplate: create output dir: %w", err)
	}

	templates := applicableTemplates(standards)
	for _, tmpl := range templates {
		path := filepath.Join(outputDir, tmpl.Filename)
		if err := os.WriteFile(path, []byte(tmpl.Content), 0o640); err != nil {
			return nil, fmt.Errorf("doctemplate: write %s: %w", path, err)
		}
		info, err := os.Stat(path)
		if err != nil {
			return nil, fmt.Errorf("doctemplate: stat %s: %w", path, err)
		}
		r.Generated = append(r.Generated, GeneratedDoc{
			TemplateID: tmpl.ID,
			Name:       tmpl.Name,
			Path:       path,
			Size:       info.Size(),
		})
		r.TotalGenerated++
	}

	r.Hash = computeHash(r)
	return r, nil
}

func computeHash(r *Report) string {
	tmp := *r
	tmp.Hash = ""
	data, err := json.Marshal(tmp)
	if err != nil {
		return ""
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

// Save writes the report to path as indented JSON.
//
//fusa:req REQ-FO-TMPL003
func Save(path string, r *Report) error {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return fmt.Errorf("doctemplate: marshal: %w", err)
	}
	if err := os.WriteFile(path, append(data, '\n'), 0o640); err != nil {
		return fmt.Errorf("doctemplate: write %s: %w", path, err)
	}
	return nil
}

// Load reads a persisted report from path.
//
//fusa:req REQ-FO-TMPL003
func Load(path string) (*Report, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, fusaops.ErrNoConfig
		}
		return nil, fmt.Errorf("doctemplate: read %s: %w", path, err)
	}
	var r Report
	if err := json.Unmarshal(data, &r); err != nil {
		return nil, fmt.Errorf("doctemplate: unmarshal %s: %w", path, err)
	}
	return &r, nil
}

// Render writes a representation of the report to w.
// Supported formats: "text", "json".
//
//fusa:req REQ-FO-TMPL004
func Render(w io.Writer, r *Report, format string) error {
	switch format {
	case "text", "":
		return renderText(w, r)
	case "json":
		enc := json.NewEncoder(w)
		enc.SetIndent("", "  ")
		return enc.Encode(r)
	default:
		return fmt.Errorf("doctemplate: unsupported format %q", format)
	}
}

func renderText(w io.Writer, r *Report) error {
	fmt.Fprintf(w, "FuSaOps Safety Documentation Templates\n")
	fmt.Fprintf(w, "=======================================\n")
	fmt.Fprintf(w, "Project:   %s\n", r.ProjectRoot)
	fmt.Fprintf(w, "Tool:      %s v%s\n", r.Tool, r.ToolVersion)
	fmt.Fprintf(w, "Standards: %s\n", strings.Join(r.Standards, ", "))
	fmt.Fprintf(w, "Output:    %s\n", r.OutputDir)
	fmt.Fprintf(w, "Generated: %s\n", r.GeneratedAt.Format("2006-01-02T15:04:05Z"))
	fmt.Fprintf(w, "Templates: %d generated\n\n", r.TotalGenerated)

	for _, d := range r.Generated {
		fmt.Fprintf(w, "  [OK] %s — %s (%d bytes)\n", d.TemplateID, d.Name, d.Size)
		fmt.Fprintf(w, "       %s\n", d.Path)
	}
	if r.Hash != "" {
		fmt.Fprintf(w, "\nIntegrity: %s\n", r.Hash)
	}
	return nil
}
